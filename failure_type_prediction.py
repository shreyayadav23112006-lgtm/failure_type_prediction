import numpy as np
import joblib
import streamlit as st

# failure_type_prediction.pkl

model = joblib.load('failure_type_prediction.pkl')

st.set_page_config(page_title="failure Type classification",layout="centered")
st.title("failure Type  classification App")
st.write("predict whether the failure is **Red** or **white** using chemical properties")


footfall = st.number_input("value of footfall",value=None)
tempMode = st.number_input("value of tempMode",value=None)
AQ = st.number_input("value of AQ",value=None)
USS = st.number_input("value of USS",value=None)
CS = st.number_input("value of CS",value=None)
VOC = st.number_input("value of VOC",value=None)
RP = st.number_input("value of total RP",value=None)
IP = st.number_input("value of IP",value=None)
Temperature = st.number_input("value of Temperature",value=None)
fail = st.number_input("value of fail",value=None)

if st.button("predict"):
  input_data = np.array([[footfall,
                          tempMode,
                          AQ,
                          USS,
                          CS,
                          VOC,
                          RP,
                          IP,
                          Temperature,
                          fail
                    ]])
  prediction = model.predict(input_data)[0]
  if prediction == 0:
    st.success("not fail")
  else:
    st.error("fail")
